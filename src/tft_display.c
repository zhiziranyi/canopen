/* ---- Public API wrappers ---- */

void TFT_SetBacklight(uint8_t brightness)
{
    if (brightness) LCD_BL_ON; else LCD_BL_OFF;
}

static void LCD_SetAddress(uint16_t x1, uint16_t y1, uint16_t x2, uint16_t y2)
{
    LCD_CS_L;
    LCD_WriteCommand(0x2A);
    LCD_WriteData16(x1);
    LCD_WriteData16(x2);
    LCD_WriteCommand(0x2B);
    LCD_WriteData16(y1);
    LCD_WriteData16(y2);
    LCD_WriteCommand(0x2C);
    while (hspi3.Instance->SR & SPI_SR_BSY);
    LCD_CS_H;
}

void TFT_SetAddrWindow(uint16_t x0, uint16_t y0, uint16_t x1, uint16_t y1)
{
    LCD_SetAddress(x0, y0, x1, y1);
}

static void LCD_Clear(uint16_t color)
{
    uint32_t i, n = 240U * 240U;

    LCD_CS_L;
    LCD_WriteCommand(0x2A);
    LCD_WriteData16(0x0000);
    LCD_WriteData16(0x00EF);  /* 239 */
    LCD_WriteCommand(0x2B);
    LCD_WriteData16(0x0000);
    LCD_WriteData16(0x00EF);  /* 239 */
    LCD_WriteCommand(0x2C);

    CLEAR_BIT(hspi3.Instance->CR1, SPI_CR1_SPE);
    SET_BIT(hspi3.Instance->CR1, SPI_CR1_DFF);
    SET_BIT(hspi3.Instance->CR1, SPI_CR1_SPE);

    for (i = 0; i < n; i++) {
        hspi3.Instance->DR = color;
        while (!(hspi3.Instance->SR & SPI_SR_TXE));
    }
    while (hspi3.Instance->SR & SPI_SR_BSY);
    LCD_CS_H;

    CLEAR_BIT(hspi3.Instance->CR1, SPI_CR1_SPE);
    CLEAR_BIT(hspi3.Instance->CR1, SPI_CR1_DFF);
    SET_BIT(hspi3.Instance->CR1, SPI_CR1_SPE);
}

void TFT_FillScreen(uint16_t color)
{
    LCD_Clear(color);
}

void TFT_PushColors(uint16_t *colors, uint32_t count)
{
    uint32_t i;

    CLEAR_BIT(hspi3.Instance->CR1, SPI_CR1_SPE);
    SET_BIT(hspi3.Instance->CR1, SPI_CR1_DFF);
    SET_BIT(hspi3.Instance->CR1, SPI_CR1_SPE);

    LCD_CS_L;
    for (i = 0; i < count; i++) {
        hspi3.Instance->DR = colors[i];
        while (!(hspi3.Instance->SR & SPI_SR_TXE));
    }
    while (hspi3.Instance->SR & SPI_SR_BSY);
    LCD_CS_H;

    CLEAR_BIT(hspi3.Instance->CR1, SPI_CR1_SPE);
    CLEAR_BIT(hspi3.Instance->CR1, SPI_CR1_DFF);
    SET_BIT(hspi3.Instance->CR1, SPI_CR1_SPE);
}

/* ---- Video frame streaming (fast, single SPI mode switch) ---- */

void TFT_StreamStart(void)
{
    LCD_CS_L;
    LCD_WriteCommand(0x2A); LCD_WriteData16(0x0000); LCD_WriteData16(0x00EF);
    LCD_WriteCommand(0x2B); LCD_WriteData16(0x0000); LCD_WriteData16(0x00EF);
    LCD_WriteCommand(0x2C);
    while (hspi3.Instance->SR & SPI_SR_BSY);

    CLEAR_BIT(hspi3.Instance->CR1, SPI_CR1_SPE);
    SET_BIT(hspi3.Instance->CR1, SPI_CR1_DFF);
    SET_BIT(hspi3.Instance->CR1, SPI_CR1_SPE);
}

void TFT_StreamPush(uint16_t *data, uint32_t count)
{
    for (uint32_t i = 0; i < count; i++) {
        hspi3.Instance->DR = data[i];
        while (!(hspi3.Instance->SR & SPI_SR_TXE));
    }
}

void TFT_StreamEnd(void)
{
    while (hspi3.Instance->SR & SPI_SR_BSY);
    LCD_CS_H;
    CLEAR_BIT(hspi3.Instance->CR1, SPI_CR1_SPE);
    CLEAR_BIT(hspi3.Instance->CR1, SPI_CR1_DFF);
    SET_BIT(hspi3.Instance->CR1, SPI_CR1_SPE);
}

