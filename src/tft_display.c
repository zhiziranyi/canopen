static uint16_t g_text_fg = COLOR_WHITE;
static uint16_t g_text_bg = COLOR_BLACK;

/* One-character render buffer (max 32x32 from reference) */
static uint16_t g_char_buf[32 * 32];

void TFT_SetTextColor(uint16_t fg, uint16_t bg)
{
    g_text_fg = fg;
    g_text_bg = bg;
}

void TFT_DrawChar(uint16_t x, uint16_t y, char c)
{
    uint16_t i = 0, row, col;
    unsigned char idx;

    if (c < 32 || c > 126) c = ' ';
    idx = (unsigned char)(c - 32);

    /* Font data is row-major: each byte = one row of 8 pixels, LSB=leftmost */
    for (row = 0; row < FONT_H; row++) {
        unsigned char data = ASCII_1608_Table[idx * FONT_H + row];
        for (col = 0; col < FONT_W; col++) {
            g_char_buf[i++] = (data & 0x01) ? g_text_fg : g_text_bg;
            data >>= 1;
        }
    }

    TFT_SetAddrWindow(x, y, x + FONT_W - 1, y + FONT_H - 1);
    TFT_PushColors(g_char_buf, FONT_W * FONT_H);
}

void TFT_DrawString(uint16_t x, uint16_t y, const char *str)
{
    while (*str && x < TFT_WIDTH) {
        if (*str == '\n') {
            x = 0;
            y += FONT_H;
            str++;
            continue;
        }
        TFT_DrawChar(x, y, *str);
        x += FONT_W;
        str++;
    }
}

/* Draw a 16x16 Chinese glyph (font is column-major, TFT expects row-major) */
void TFT_DrawChar16(uint16_t x, uint16_t y, const uint8_t *bmp)
{
    for (int row = 0; row < 16; row++) {
        for (int col = 0; col < 16; col++) {
            int byte_ofs = col * 2 + row / 8;
            int bit = row % 8;
            uint8_t on = (bmp[byte_ofs] >> bit) & 1;
            g_char_buf[row * 16 + col] = on ? g_text_fg : g_text_bg;
        }
    }
    TFT_SetAddrWindow(x, y, x + 15, y + 15);
    TFT_PushColors(g_char_buf, 256);
}

/* UTF-8 text renderer: ASCII 8x16, Chinese 16x16, wraps at TFT_WIDTH */
void TFT_DrawUTF8(uint16_t x0, uint16_t y0, const uint8_t *data, unsigned int len)
{
    uint16_t x = x0, y = y0;
    unsigned int pos = 0;

    while (pos < len && y + 16 <= TFT_HEIGHT) {
        uint8_t c = data[pos];
        uint32_t cp;

        /* Decode UTF-8 */
        if (c < 0x80) { cp = c; pos++; }
        else if ((c & 0xE0) == 0xC0 && pos + 1 < len) {
            cp = ((c & 0x1F) << 6) | (data[pos + 1] & 0x3F);
            pos += 2;
        }
        else if ((c & 0xF0) == 0xE0 && pos + 2 < len) {
            cp = ((c & 0x0F) << 12) | ((data[pos + 1] & 0x3F) << 6) | (data[pos + 2] & 0x3F);
            pos += 3;
        }
        else { pos++; cp = 0xFFFD; } /* skip invalid byte */

        /* Handle newline */
        if (cp == '\n') { x = x0; y += 16; continue; }
        if (cp == '\r') continue;

        if (cp < 0x80) {
            /* ASCII: 8px wide */
            if (x + 8 > TFT_WIDTH) { x = x0; y += 16; }
            if (y + 16 > TFT_HEIGHT) break;
            TFT_DrawChar(x, y, (char)cp);
            x += 8;
        } else {
            /* Chinese/CJK: 16px wide */
            if (x + 16 > TFT_WIDTH) { x = x0; y += 16; }
            if (y + 16 > TFT_HEIGHT) break;
            const uint8_t *bmp = cn_font_lookup((uint16_t)cp);
            if (bmp) {
                TFT_DrawChar16(x, y, bmp);
            }
            x += 16;
        }
    }
}
