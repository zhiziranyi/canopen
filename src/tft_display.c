/* SPI handle — must match reference's hspi3 usage */
SPI_HandleTypeDef hspi3;

/* ---- Pin definitions (same as reference) ---- */

#define LCD_SCK_PIN         GPIO_PIN_3
#define LCD_SCK_PORT        GPIOB
#define LCD_SDA_PIN         GPIO_PIN_5
#define LCD_SDA_PORT        GPIOB
#define LCD_CS_PIN          GPIO_PIN_11
#define LCD_CS_PORT         GPIOD
#define LCD_DC_PIN          GPIO_PIN_12
#define LCD_DC_PORT         GPIOD
#define LCD_BL_PIN          GPIO_PIN_13
#define LCD_BL_PORT         GPIOD

#define LCD_CS_H    (LCD_CS_PORT->BSRR = LCD_CS_PIN)
#define LCD_CS_L    (LCD_CS_PORT->BSRR = (uint32_t)LCD_CS_PIN << 16U)
#define LCD_DC_CMD  HAL_GPIO_WritePin(LCD_DC_PORT, LCD_DC_PIN, GPIO_PIN_RESET)
#define LCD_DC_DATA HAL_GPIO_WritePin(LCD_DC_PORT, LCD_DC_PIN, GPIO_PIN_SET)
#define LCD_BL_ON   HAL_GPIO_WritePin(LCD_BL_PORT, LCD_BL_PIN, GPIO_PIN_SET)
#define LCD_BL_OFF  HAL_GPIO_WritePin(LCD_BL_PORT, LCD_BL_PIN, GPIO_PIN_RESET)

/* ---- HAL_SPI_MspInit (exact copy from reference) ---- */

void HAL_SPI_MspInit(SPI_HandleTypeDef *hspi)
{
    GPIO_InitTypeDef GPIO_InitStruct = {0};
    if (hspi->Instance == SPI3) {
        __HAL_RCC_SPI3_CLK_ENABLE();
        __HAL_RCC_GPIOB_CLK_ENABLE();
        __HAL_RCC_GPIOD_CLK_ENABLE();

        GPIO_InitStruct.Pin       = LCD_SCK_PIN;
        GPIO_InitStruct.Mode      = GPIO_MODE_AF_PP;
        GPIO_InitStruct.Pull      = GPIO_NOPULL;
        GPIO_InitStruct.Speed     = GPIO_SPEED_FREQ_VERY_HIGH;
        GPIO_InitStruct.Alternate = GPIO_AF6_SPI3;
        HAL_GPIO_Init(LCD_SCK_PORT, &GPIO_InitStruct);

        GPIO_InitStruct.Pin = LCD_SDA_PIN;
        HAL_GPIO_Init(LCD_SDA_PORT, &GPIO_InitStruct);

        GPIO_InitStruct.Pin   = LCD_CS_PIN;
        GPIO_InitStruct.Mode  = GPIO_MODE_OUTPUT_PP;
        GPIO_InitStruct.Speed = GPIO_SPEED_FREQ_HIGH;
        HAL_GPIO_Init(LCD_CS_PORT, &GPIO_InitStruct);

        GPIO_InitStruct.Pin   = LCD_BL_PIN;
        GPIO_InitStruct.Speed = GPIO_SPEED_FREQ_LOW;
        HAL_GPIO_Init(LCD_BL_PORT, &GPIO_InitStruct);

        GPIO_InitStruct.Pin   = LCD_DC_PIN;
        GPIO_InitStruct.Speed = GPIO_SPEED_FREQ_HIGH;
        HAL_GPIO_Init(LCD_DC_PORT, &GPIO_InitStruct);

        LCD_DC_DATA;
        LCD_CS_H;
        LCD_BL_OFF;
    }
}

/* ---- MX_SPI3_Init (exact copy from reference) ---- */

static void MX_SPI3_Init(void)
{
    hspi3.Instance               = SPI3;
    hspi3.Init.Mode              = SPI_MODE_MASTER;
    hspi3.Init.Direction         = SPI_DIRECTION_1LINE;
    hspi3.Init.DataSize          = SPI_DATASIZE_8BIT;
    hspi3.Init.CLKPolarity       = SPI_POLARITY_LOW;
    hspi3.Init.CLKPhase          = SPI_PHASE_1EDGE;
    hspi3.Init.NSS               = SPI_NSS_SOFT;
    hspi3.Init.BaudRatePrescaler = SPI_BAUDRATEPRESCALER_2;
    hspi3.Init.FirstBit          = SPI_FIRSTBIT_MSB;
    hspi3.Init.TIMode            = SPI_TIMODE_DISABLE;
    hspi3.Init.CRCCalculation    = SPI_CRCCALCULATION_DISABLE;
    HAL_SPI_Init(&hspi3);
    __HAL_SPI_ENABLE(&hspi3);
    SPI_1LINE_TX(&hspi3);
}

/* ---- LCD write functions (exact copy from reference) ---- */

static void LCD_WriteCommand(uint8_t cmd)
{
    while ((hspi3.Instance->SR & SPI_SR_BSY));
    LCD_DC_CMD;
    hspi3.Instance->DR = cmd;
    while (!(hspi3.Instance->SR & SPI_SR_TXE));
    while ((hspi3.Instance->SR & SPI_SR_BSY));
    LCD_DC_DATA;
}

static void LCD_WriteData8(uint8_t data)
{
    hspi3.Instance->DR = data;
    while (!(hspi3.Instance->SR & SPI_SR_TXE));
}

static void LCD_WriteData16(uint16_t data)
{
    hspi3.Instance->DR = (uint8_t)(data >> 8);
    while (!(hspi3.Instance->SR & SPI_SR_TXE));
    hspi3.Instance->DR = (uint8_t)(data & 0xFF);
    while (!(hspi3.Instance->SR & SPI_SR_TXE));
}

